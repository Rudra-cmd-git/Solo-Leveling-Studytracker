#!/usr/bin/env node
/**
 * Concatenate every migration into one file that can be pasted into the
 * Supabase SQL editor in a single run.
 *
 * The migrations are written to be applied in filename order and each one is
 * idempotent against a fresh database, so a single sequential run is equivalent
 * to running them one at a time.
 *
 * Usage:
 *   npm run db:bundle
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";

const dir = resolve(process.cwd(), "supabase/migrations");
const files = readdirSync(dir)
  .filter((name) => name.endsWith(".sql"))
  .sort((a, b) => a.localeCompare(b, "en"));

if (files.length === 0) {
  console.error("No migrations found in supabase/migrations.");
  process.exit(1);
}

const banner = `-- ============================================================================
-- HUNTER SYSTEM - complete database setup
-- ----------------------------------------------------------------------------
-- Generated by "npm run db:bundle" from supabase/migrations/*.sql.
-- Do not edit by hand: edit the individual migrations and regenerate.
--
-- How to apply, once, against a fresh Supabase project:
--   1. Supabase dashboard -> SQL Editor -> New query
--   2. Paste this entire file
--   3. Run
--
-- The script is ordered and self-contained. It creates the schema, the
-- progression engine, Row Level Security policies, the leaderboard, the
-- catalog seed, analytics, avatar storage, friends, guilds, seasons and the
-- moderation console.
--
-- Files included:
${files.map((name, index) => `--   ${String(index + 1).padStart(2, " ")}. ${name}`).join("\n")}
-- ============================================================================

`;

const body = files
  .map((name) => {
    const sql = readFileSync(resolve(dir, name), "utf8").trimEnd();
    return `\n\n-- ############################################################################\n-- ## ${name}\n-- ############################################################################\n\n${sql}\n`;
  })
  .join("");

const target = resolve(process.cwd(), "supabase/apply_all.sql");
writeFileSync(target, banner + body.trimStart(), "utf8");

const bytes = readFileSync(target).length;
console.log(`Bundled ${files.length} migrations -> supabase/apply_all.sql (${(bytes / 1024).toFixed(0)} KB)`);
console.log("Paste it into Supabase > SQL Editor > New query, then Run.");
